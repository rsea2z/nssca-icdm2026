from __future__ import annotations

import argparse
import csv
import json
import statistics
from pathlib import Path
from typing import Any


EXPECTED_CLASSES = {
    "mvtec": 15,
    "visa": 12,
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Summarize PromptAD aligned CSV outputs.")
    parser.add_argument("--root", default="runs/strong_baselines/promptad")
    parser.add_argument("--output-json", default="runs/strong_baselines/promptad/summary.json")
    parser.add_argument("--output-md", default="docs/promptad_direct_baseline.md")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    root = Path(args.root)
    runs = [parse_csv(path, root) for path in sorted(root.glob("*/k_*/csv/Seed_*-results.csv"))]
    summary = build_summary(runs)

    output_json = Path(args.output_json)
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")

    output_md = Path(args.output_md)
    output_md.parent.mkdir(parents=True, exist_ok=True)
    output_md.write_text(render_markdown(summary), encoding="utf-8")

    print(output_json)
    print(output_md)


def parse_csv(path: Path, root: Path) -> dict[str, Any]:
    relative = path.relative_to(root)
    dataset = relative.parts[0]
    shot = int(relative.parts[1].removeprefix("k_"))
    seed = int(path.stem.removeprefix("Seed_").removesuffix("-results"))

    rows = []
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        class_key = reader.fieldnames[0] if reader.fieldnames else ""
        for item in reader:
            rows.append(
                {
                    "class": item[class_key],
                    "image_auroc": float(item["i_roc"]) / 100.0,
                    "pixel_auroc": float(item["p_roc"]) / 100.0,
                    "fpr95": float(item["i_fpr95"]) / 100.0,
                }
            )

    expected = EXPECTED_CLASSES.get(dataset)
    return {
        "dataset": dataset,
        "shot": shot,
        "seed": seed,
        "path": str(path),
        "num_classes": len(rows),
        "expected_classes": expected,
        "complete": expected is None or len(rows) == expected,
        "image_auroc": mean(row["image_auroc"] for row in rows),
        "pixel_auroc": mean(row["pixel_auroc"] for row in rows),
        "fpr95": mean(row["fpr95"] for row in rows),
        "worst_image_class": min(rows, key=lambda row: row["image_auroc"]) if rows else None,
        "worst_fpr_class": max(rows, key=lambda row: row["fpr95"]) if rows else None,
        "classes": rows,
    }


def build_summary(runs: list[dict[str, Any]]) -> dict[str, Any]:
    groups = []
    keys = sorted({(run["dataset"], run["shot"]) for run in runs})
    for dataset, shot in keys:
        items = [run for run in runs if run["dataset"] == dataset and run["shot"] == shot]
        groups.append(
            {
                "dataset": dataset,
                "shot": shot,
                "num_seeds": len(items),
                "seeds": sorted(run["seed"] for run in items),
                "all_complete": all(run["complete"] for run in items),
                "image_auroc_mean": mean(run["image_auroc"] for run in items),
                "image_auroc_std": stdev(run["image_auroc"] for run in items),
                "pixel_auroc_mean": mean(run["pixel_auroc"] for run in items),
                "pixel_auroc_std": stdev(run["pixel_auroc"] for run in items),
                "fpr95_mean": mean(run["fpr95"] for run in items),
                "fpr95_std": stdev(run["fpr95"] for run in items),
            }
        )
    return {"num_runs": len(runs), "groups": groups, "runs": runs}


def render_markdown(summary: dict[str, Any]) -> str:
    lines = [
        "# PromptAD Direct Baseline",
        "",
        "Generated by `scripts/summarize_promptad_results.py` from `runs/strong_baselines/promptad`.",
        "",
        "The PromptAD classification route reports image AUROC, pixel AUROC from its score maps, and image FPR@95TPR. Pixel AUROC should only be used after eval logs confirm non-zero `p_roc` values.",
        "",
        "## Aggregate",
        "",
        "| Dataset | Shot | Seeds | Complete | Image AUROC | Pixel AUROC | FPR@95TPR |",
        "|---|---:|---|---|---:|---:|---:|",
    ]
    for group in summary["groups"]:
        lines.append(
            "| {dataset} | {shot} | {seeds} | {complete} | {image} | {pixel} | {fpr} |".format(
                dataset=group["dataset"],
                shot=group["shot"],
                seeds=",".join(str(seed) for seed in group["seeds"]),
                complete="yes" if group["all_complete"] else "no",
                image=fmt_mean_std(group["image_auroc_mean"], group["image_auroc_std"], group["num_seeds"]),
                pixel=fmt_mean_std(group["pixel_auroc_mean"], group["pixel_auroc_std"], group["num_seeds"]),
                fpr=fmt_mean_std(group["fpr95_mean"], group["fpr95_std"], group["num_seeds"]),
            )
        )

    lines.extend(
        [
            "",
            "## Per Run",
            "",
            "| Dataset | Shot | Seed | Classes | Image AUROC | Pixel AUROC | FPR@95TPR | Worst image class | Worst FPR class |",
            "|---|---:|---:|---:|---:|---:|---:|---|---|",
        ]
    )
    for run in summary["runs"]:
        worst_image = run["worst_image_class"] or {}
        worst_fpr = run["worst_fpr_class"] or {}
        lines.append(
            "| {dataset} | {shot} | {seed} | {classes}/{expected} | {image} | {pixel} | {fpr} | {wi} | {wf} |".format(
                dataset=run["dataset"],
                shot=run["shot"],
                seed=run["seed"],
                classes=run["num_classes"],
                expected=run["expected_classes"] or "?",
                image=fmt(run["image_auroc"]),
                pixel=fmt(run["pixel_auroc"]),
                fpr=fmt(run["fpr95"]),
                wi=format_class_metric(worst_image, "image_auroc"),
                wf=format_class_metric(worst_fpr, "fpr95"),
            )
        )
    lines.append("")
    return "\n".join(lines)


def mean(values: Any) -> float | None:
    items = [float(value) for value in values]
    if not items:
        return None
    return statistics.fmean(items)


def stdev(values: Any) -> float | None:
    items = [float(value) for value in values]
    if len(items) < 2:
        return 0.0 if items else None
    return statistics.stdev(items)


def fmt(value: float | None) -> str:
    if value is None:
        return "-"
    return f"{value:.4f}"


def fmt_mean_std(mean_value: float | None, std_value: float | None, count: int) -> str:
    if mean_value is None:
        return "-"
    if count < 2 or std_value is None:
        return fmt(mean_value)
    return f"{mean_value:.4f} +/- {std_value:.4f}"


def format_class_metric(row: dict[str, Any], metric: str) -> str:
    if not row:
        return "-"
    return f"{row['class']} ({fmt(row[metric])})"


if __name__ == "__main__":
    main()
